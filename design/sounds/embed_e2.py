"""Embed the selected audition exactly, trimming only trailing digital silence."""
import array
import hashlib
import json
from pathlib import Path
import sys
import wave

ROOT = Path(__file__).resolve().parent


def main():
    selected = json.loads((ROOT/'manifest-fc.json').read_text(encoding='utf8'))['palettes']['E2']
    lines = ['// Generated by design/sounds/embed_e2.py; selected E2, 16000 Hz mono PCM16.',
             '#pragma once', '#include <stdint.h>']
    for state, entry in zip(('running','question','done'), selected['sounds']):
        source = ROOT/entry['file']
        assert hashlib.sha256(source.read_bytes()).hexdigest() == entry['sha256']
        with wave.open(str(source),'rb') as wav:
            assert (wav.getframerate(),wav.getnchannels(),wav.getsampwidth()) == (16000,1,2)
            data = array.array('h',wav.readframes(wav.getnframes()))
        if sys.byteorder != 'little':
            data.byteswap()
        end = max(i for i,x in enumerate(data) if x) + 33
        assert all(x == 0 for x in data[end:])
        samples = data[:end]
        assert max(map(abs,samples)) < 11469
        lines.append(f'static const int16_t sound_{state}[] = {{')
        for offset in range(0,len(samples),24):
            lines.append(','.join(map(str,samples[offset:offset+24]))+',')
        lines.append('};')
        print(f'PASS E2 {state}: exact PCM prefix, {len(samples)} samples, SHA256 verified')
    target = ROOT.parents[1]/'src'/'sound_samples.h'
    target.write_text('\n'.join(lines)+'\n',encoding='ascii')


if __name__ == '__main__':
    main()
